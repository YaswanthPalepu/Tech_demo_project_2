def _write_if_absent(path: Path, content: str) -> bool:
    if path.exists(): return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8"); return True

def _module_name(fp: Path, root: Path) -> str:
    return ".".join(fp.relative_to(root).with_suffix("").parts)

def generate_pytests(repo_root: Path, analyses: List[Dict[str, Any]], out_dir: Path) -> List[Path]:
    unit_dir = out_dir / "unit"
    integ_dir = out_dir / "integration"
    e2e_dir  = out_dir / "e2e"
    created: List[Path] = []

    # Django project-level tests
    dj = _detect_django(repo_root)
    if dj:
        all_urls: List[str] = []
        for up in dj.urls_files:
            all_urls.extend(_django_urls_from_file(up))
        _ensure_django_conftest(out_dir, dj.settings_module)
        ctx = {"settings_module": dj.settings_module, "urls": all_urls[:200]}
        ai_in = _ai_integ("django", ctx) or _django_integration(all_urls)
        ai_e2e = _ai_e2e("django", ctx) or _django_e2e(all_urls)
        if _write_if_absent(integ_dir / "test_django_integration.py", ai_in): created.append(integ_dir / "test_django_integration.py")
        if _write_if_absent(e2e_dir / "test_django_e2e.py", ai_e2e): created.append(e2e_dir / "test_django_e2e.py")

    for a in analyses:
        path = a.get("path", "")
        if not path: continue
        if "tests/" in path or "/migrations/" in path or "\\migrations\\" in path:
            continue
        src = a.get("source", "")
        fp = Path(path); module = _module_name(fp, repo_root)

        # ----- UNIT -----
        code = _ai_unit(module, a) or _unit_fallback(module, a)
        uf = unit_dir / f"test_{fp.stem}.py"
        if _write_if_absent(uf, code): created.append(uf)

        # ----- INTEGRATION/E2E per module -----
        fapi = _extract_fastapi(src)
        if fapi:
            ctx = {"module": module, "app_name": fapi.app_name, "routes": [{"m": r.method, "p": r.path} for r in fapi.routes[:100]]}
            in_code = _ai_integ("fastapi", ctx) or _fastapi_integration(module, fapi)
            e2e_code = _ai_e2e("fastapi", ctx) or _fastapi_e2e(module, fapi)
            if _write_if_absent(integ_dir / f"test_{fp.stem}_integration.py", in_code): created.append(integ_dir / f"test_{fp.stem}_integration.py")
            if _write_if_absent(e2e_dir / f"test_{fp.stem}_e2e.py", e2e_code): created.append(e2e_dir / f"test_{fp.stem}_e2e.py")
            continue

        flask_m = _extract_flask(src)
        if flask_m:
            ctx = {"module": module, "app_name": flask_m.app_name, "routes": [r.path for r in flask_m.routes[:100]]}
            in_code = _ai_integ("flask", ctx) or _flask_integration(module, flask_m)
            e2e_code = _ai_e2e("flask", ctx) or _flask_e2e(module, flask_m)
            if _write_if_absent(integ_dir / f"test_{fp.stem}_integration.py", in_code): created.append(integ_dir / f"test_{fp.stem}_integration.py")
            if _write_if_absent(e2e_dir / f"test_{fp.stem}_e2e.py", e2e_code): created.append(e2e_dir / f"test_{fp.stem}_e2e.py")
            continue

        # CLI Typer
        m = TYPER_APP_RE.search(src)
        if m:
            app_name = m.group(1)
            ctx = {"module": module, "app_name": app_name}
            in_code = _ai_integ("typer", ctx) or _cli_typer_integration(module, app_name)
            e2e_code = _ai_e2e("typer", ctx) or in_code
            if _write_if_absent(integ_dir / f"test_{fp.stem}_integration.py", in_code): created.append(integ_dir / f"test_{fp.stem}_integration.py")
            if _write_if_absent(e2e_dir / f"test_{fp.stem}_e2e.py", e2e_code): created.append(e2e_dir / f"test_{fp.stem}_e2e.py")
            continue

        # CLI Click
        if _has_click(src):
            ctx = {"module": module}
            in_code = _ai_integ("click", ctx) or _cli_click_integration(module)
            e2e_code = _ai_e2e("click", ctx) or in_code
            if _write_if_absent(integ_dir / f"test_{fp.stem}_integration.py", in_code): created.append(integ_dir / f"test_{fp.stem}_integration.py")
            if _write_if_absent(e2e_dir / f"test_{fp.stem}_e2e.py", e2e_code): created.append(e2e_dir / f"test_{fp.stem}_e2e.py")
            continue

        # CLI argparse
        if _has_argparse(src):
            ctx = {"module": module}
            in_code = _ai_integ("argparse", ctx) or _cli_argparse_integration(module)
            e2e_code = _ai_e2e("argparse", ctx) or in_code
            if _write_if_absent(integ_dir / f"test_{fp.stem}_integration.py", in_code): created.append(integ_dir / f"test_{fp.stem}_integration.py")
            if _write_if_absent(e2e_dir / f"test_{fp.stem}_e2e.py", e2e_code): created.append(e2e_dir / f"test_{fp.stem}_e2e.py")
            continue

    return created
