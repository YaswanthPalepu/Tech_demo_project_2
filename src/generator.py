# ---- Heuristics for frameworks ----
FASTAPI_APP_RE = re.compile(r"\b([A-Za-z_][\w]*)\s*=\s*FastAPI\s*\(")
FASTAPI_ROUTE_RE = re.compile(r"@\s*([A-Za-z_][\w\.]*)\.(get|post|put|delete|patch)\s*\(\s*(['\"])(.*?)\3")

FLASK_APP_RE = re.compile(r"\b([A-Za-z_][\w]*)\s*=\s*Flask\s*\(")
FLASK_ROUTE_RE = re.compile(r"@\s*([A-Za-z_][\w\.]*)\.route\s*\(\s*(['\"])(.*?)\2")

DJANGO_URLS_PATH_RE = re.compile(r"""path\(\s*['\"]([^'\"]+)['\"]""")
DJANGO_URLS_REPATH_RE = re.compile(r"""re_path\(\s*[r]?['\"]([^'\"]+)['\"]""")

TYPER_APP_RE = re.compile(r"\b([A-Za-z_][\w]*)\s*=\s*typer\.Typer\s*\(")
ARGPARSE_RE = re.compile(r"\bargparse\.ArgumentParser\s*\(")

@dataclass
class Route:
    owner: str
    method: str
    path: str

@dataclass
class FastAPIModule:
    app_name: str
    routes: List[Route]

@dataclass
class FlaskModule:
    app_name: str
    routes: List[Route]

@dataclass
class DjangoProject:
    settings_module: Optional[str]
    urls_files: List[Path]

def _extract_fastapi(source: str) -> Optional[FastAPIModule]:
    m = FASTAPI_APP_RE.search(source)
    app_name = m.group(1) if m else "app"
    routes = [Route(owner=o.split(".")[-1], method=meth.lower(), path=p)
              for o, meth, _, p in FASTAPI_ROUTE_RE.findall(source)]
    return FastAPIModule(app_name, routes) if routes else None

def _extract_flask(source: str) -> Optional[FlaskModule]:
    m = FLASK_APP_RE.search(source)
    app_name = m.group(1) if m else "app"
    routes = [Route(owner=o.split(".")[-1], method="", path=p)
              for o, _, p in FLASK_ROUTE_RE.findall(source)]
    return FlaskModule(app_name, routes) if routes else None

def _detect_django(repo_root: Path) -> Optional[DjangoProject]:
    candidates = []
    for p in repo_root.rglob("settings.py"):
        if "venv" in p.parts or ".venv" in p.parts:
            continue
        if (p.parent / "urls.py").exists():
            candidates.append(p)
    settings_module = None
    if candidates:
        best = min(candidates, key=lambda p: len(p.parts))
        rel = best.relative_to(repo_root).with_suffix("")
        settings_module = ".".join(rel.parts)
    urls_files = [p for p in repo_root.rglob("urls.py") if "venv" not in p.parts and ".venv" not in p.parts]
    if settings_module or urls_files:
        return DjangoProject(settings_module, urls_files)
    return None

def _django_urls_from_file(p: Path) -> List[str]:
    try:
        src = p.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return []
    urls = []
    for m in DJANGO_URLS_PATH_RE.finditer(src):
        u = m.group(1)
        urls.append(u if u.startswith("/") else "/" + u)
    for m in DJANGO_URLS_REPATH_RE.finditer(src):
        urls.append(f"[re_path]{m.group(1)}")
    seen = set(); out = []
    for u in urls:
        if u not in seen:
            seen.add(u); out.append(u)
    return out

def _has_click(source: str) -> bool:
    return "import click" in source or "from click" in source

def _has_typer(source: str) -> Optional[str]:
    m = TYPER_APP_RE.search(source)
    return m.group(1) if m else None

def _has_argparse(source: str) -> bool:
    return bool(ARGPARSE_RE.search(source))

