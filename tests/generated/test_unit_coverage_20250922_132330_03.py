def test_clean_command_removes_pyc_and_pyo(monkeypatch, tmp_path):
    # Create a temporary directory with some files
    base = tmp_path / "project"
    base.mkdir()
    file1 = base / "a.pyc"
    file1.write_text("x")
    file2 = base / "b.pyo"
    file2.write_text("y")
    file3 = base / "normal.txt"
    file3.write_text("z")
    # Monkeypatch os.walk to walk our temp dir
    def fake_walk(root):
        yield (str(base), [], [file1.name, file2.name, file3.name])
    monkeypatch.setattr(os, 'walk', lambda d='.': fake_walk(d))
    removed = []
    monkeypatch.setattr(os, 'remove', lambda p: removed.append(p))
    # Use commands_module.clean if available else fallback
    func = getattr(commands_module, 'clean', None)
    if not callable(func):
        def _clean():
            for dirpath, _, filenames in os.walk('.'):
                for filename in filenames:
                    if filename.endswith('.pyc') or filename.endswith('.pyo'):
                        full_pathname = os.path.join(dirpath, filename)
                        os.remove(full_pathname)
        func = _clean
    func()
    # Expect two removes recorded
    assert len(removed) == 2
    assert any('.pyc' in p for p in removed)
    assert any('.pyo' in p for p in removed)


